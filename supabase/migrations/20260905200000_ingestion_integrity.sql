-- Durable run/record audit and idempotent persistence. No seed data.
create table if not exists public.ingestion_runs (
  id bigint generated by default as identity primary key,
  run_key text not null unique,
  county_id text not null references public.counties(county_id),
  run_type text not null default 'manual',
  status text not null default 'running' check (status in ('running','completed','partial','failed','skipped')),
  source_url text,
  started_at timestamptz not null default now(),
  heartbeat_at timestamptz not null default now(),
  finished_at timestamptz,
  records_seen integer not null default 0 check (records_seen >= 0),
  records_normalized integer not null default 0 check (records_normalized >= 0),
  records_persisted integer not null default 0 check (records_persisted >= 0),
  records_rejected integer not null default 0 check (records_rejected >= 0),
  records_held integer not null default 0 check (records_held >= 0),
  records_skipped integer not null default 0 check (records_skipped >= 0),
  deals_persisted integer not null default 0 check (deals_persisted >= 0),
  records_failed integer not null default 0 check (records_failed >= 0),
  records_published integer not null default 0 check (records_published >= 0),
  error_message text,
  metadata jsonb not null default '{}'::jsonb,
  unique(id, county_id),
  check ((status = 'running') = (finished_at is null))
);

