create or replace function public.finite_number(value numeric)
returns boolean language sql immutable set search_path=public as $$
  select value is not null and value::text not in ('NaN','Infinity','-Infinity');
$$;

-- Replace comparables in one transaction; DELETE+POST over REST is not atomic.
create or replace function public.replace_deal_comps(p_deal_id bigint, p_comps jsonb)
returns integer language plpgsql security invoker set search_path = public as $$
declare inserted integer;
begin
  if p_comps is null or jsonb_typeof(p_comps) is distinct from 'array' or jsonb_array_length(p_comps) > 100 then
    raise exception 'Invalid comparable collection';
  end if;
  perform 1 from public.deals where id=p_deal_id for update;
  if not found then raise exception 'Deal not found'; end if;
  if exists (select 1 from jsonb_array_elements(p_comps) c where
      nullif(c->>'source_url','') is null or nullif(c->>'source_record_id','') is null
      or not public.finite_number((c->>'sale_price')::numeric) or (c->>'sale_price')::numeric <= 0
      or not public.finite_number((c->>'lot_size_acres')::numeric) or (c->>'lot_size_acres')::numeric <= 0
      or not public.finite_number((c->>'distance_miles')::numeric) or (c->>'distance_miles')::numeric < 0
      or nullif(c->>'sale_date','') is null) then
    raise exception 'Invalid comparable evidence';
  end if;
  update public.deals set verification_status='pending_review', verified_at=null where id=p_deal_id;
  delete from public.comps where deal_id=p_deal_id;
  insert into public.comps(deal_id,address,sale_price,sale_date,distance_miles,lot_size_acres,price_per_acre,
    source_url,source_record_id,source_apn,county_id,sale_qualified,vacant_at_sale,ingestion_record_id)
  select p_deal_id,c.address,c.sale_price,c.sale_date,c.distance_miles,c.lot_size_acres,c.sale_price/c.lot_size_acres,
    c.source_url,c.source_record_id,c.source_apn,c.county_id,c.sale_qualified,c.vacant_at_sale,c.ingestion_record_id
  from jsonb_to_recordset(p_comps) as c(address text,sale_price numeric,sale_date timestamptz,distance_miles numeric,
    lot_size_acres numeric,price_per_acre numeric,source_url text,source_record_id text,source_apn text,
    county_id text,sale_qualified boolean,vacant_at_sale boolean,ingestion_record_id bigint);
  get diagnostics inserted = row_count;
  return inserted;
end;
$$;
revoke all on function public.replace_deal_comps(bigint,jsonb) from public, anon, authenticated;
grant execute on function public.replace_deal_comps(bigint,jsonb) to service_role;


create or replace function public.hold_deals_for_parcels(p_county_id text, p_apns text[])
returns integer language plpgsql security invoker set search_path=public as $$
declare changed integer;
begin
  if coalesce(array_length(p_apns,1),0)>250 then raise exception 'Parcel batch exceeds limit'; end if;
  update public.deals d set verification_status='pending_review',verified_at=null,verification_expires_at=null
    from public.properties p where p.id=d.property_id and p.county_id=p_county_id and p.apn=any(p_apns);
  get diagnostics changed=row_count;
  return changed;
end;
$$;
revoke all on function public.hold_deals_for_parcels(text,text[]) from public, anon, authenticated;
grant execute on function public.hold_deals_for_parcels(text,text[]) to service_role;
